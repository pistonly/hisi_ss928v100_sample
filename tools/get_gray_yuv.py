import cv2
from pathlib import Path
import argparse
import numpy as np



def BGR2yuv420sp(img, imgH, imgW):
    img = cv2.resize(img, (imgW, imgH))

    # BGR to YUV420sp
    yuv = cv2.cvtColor(img, cv2.COLOR_BGR2YUV_I420)
    h, w = yuv.shape
    h_plane = h // 3
    yuv_sp = yuv.copy()
    uv_sp = yuv_sp[h_plane * 2:].reshape(2, h_plane // 2, w).transpose(1, 2, 0).reshape(h_plane, -1)
    yuv_sp[h_plane * 2:] = uv_sp
    return yuv_sp

gray_image = np.ones((16, 16, 3), dtype=np.uint8)
gray_image *= 114

yuv = BGR2yuv420sp(gray_image, 16, 16)
